      and columns.column_name = 'state_data';

    if state_type is distinct from 'jsonb' then
        execute '
            alter table public.user_profiles
            alter column state_data type jsonb
            using public._ns_safe_jsonb(state_data::text)
        ';
    end if;
end
$$;

