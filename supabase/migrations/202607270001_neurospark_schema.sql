-- ---------------------------------------------------------------------------
-- 2. Recuperación no destructiva de una tabla equivalente renombrada.
--    Solo se consideran nombres históricos conocidos y columnas compatibles.
-- ---------------------------------------------------------------------------

do $$
declare
    candidate text;
    has_email boolean;
    has_state boolean;
    migrated_count bigint;
begin
    foreach candidate in array array['profiles', 'user_profile', 'usuarios_perfiles']
    loop
        if to_regclass(format('public.%I', candidate)) is null then
            continue;
        end if;

        select exists (
            select 1 from information_schema.columns
            where table_schema = 'public'
              and table_name = candidate
              and column_name = 'email'
        ) into has_email;

        select exists (
            select 1 from information_schema.columns
            where table_schema = 'public'
              and table_name = candidate
              and column_name = 'state_data'
        ) into has_state;

        if has_email and has_state then
            execute format(
                'insert into public.user_profiles (email, user_email, state_data)
                 select source.email::text,
                        source.email::text,
                        public._ns_safe_jsonb(source.state_data::text)
                 from public.%I as source
                 where source.email is not null
                   and not exists (
                       select 1 from public.user_profiles as target
                       where lower(coalesce(target.user_email, target.email)) =
                             lower(source.email::text)
                   )',
                candidate
            );
            get diagnostics migrated_count = row_count;
            raise notice 'Tabla equivalente public.% detectada: % filas copiadas sin eliminar el origen.',
                candidate, migrated_count;
        else
            raise notice 'Tabla public.% detectada, pero no contiene email y state_data; no fue modificada.',
                candidate;
        end if;
    end loop;
end
$$;

-- ---------------------------------------------------------------------------
-- 3. Backfill de identidades desde auth.users.
-- ---------------------------------------------------------------------------

update public.user_profiles
set user_email = coalesce(nullif(btrim(user_email), ''), nullif(btrim(email), ''))
where user_email is null or btrim(user_email) = '';

update public.user_profiles
set email = coalesce(nullif(btrim(email), ''), nullif(btrim(user_email), ''))
where email is null or btrim(email) = '';

update public.user_profiles as profile
set user_id = auth_user.id
from auth.users as auth_user
where profile.user_id is null
  and auth_user.email is not null
  and lower(auth_user.email) = lower(coalesce(profile.user_email, profile.email));

update public.correos as link
set child_user_id = auth_user.id
from auth.users as auth_user
where link.child_user_id is null
  and auth_user.email is not null
  and lower(auth_user.email) = lower(link.user_email);

update public.correos as link
set parent_user_id = auth_user.id
from auth.users as auth_user
where link.parent_user_id is null
  and auth_user.email is not null
  and lower(auth_user.email) = lower(link.parent_email);

-- Se elige primero un vínculo principal determinista. Así el backfill siguiente
-- nunca toma al azar una de varias filas antiguas para el mismo hijo.
with ranked as (
    select link.id,
           row_number() over (
               partition by link.child_user_id
               order by link.is_primary desc, link.updated_at desc, link.id
           ) as position
    from public.correos as link
    where link.child_user_id is not null
)
update public.correos as link
set is_primary = ranked.position = 1
from ranked
where link.id = ranked.id
  and link.is_primary is distinct from (ranked.position = 1);

update public.user_profiles as profile
set parent_email = link.parent_email,
    parent_user_id = coalesce(profile.parent_user_id, link.parent_user_id),
    alias = coalesce(profile.alias, link.alias),
    full_name = coalesce(profile.full_name, link.full_name),
    age = coalesce(profile.age, link.age),
    mode = coalesce(profile.mode, link.mode)
from public.correos as link
where profile.user_id = link.child_user_id
  and link.is_primary;

-- ---------------------------------------------------------------------------
-- 4. Auditoría y resolución no destructiva de duplicados.
--    Se mantiene una fila principal determinista; ninguna fila se elimina.
-- ---------------------------------------------------------------------------

with ranked as (
    select profile.id,
           row_number() over (
               partition by profile.user_id
               order by profile.is_primary desc, profile.updated_at desc, profile.id
           ) as position
    from public.user_profiles as profile
    where profile.user_id is not null
)
update public.user_profiles as profile
set is_primary = ranked.position = 1
from ranked
where profile.id = ranked.id
  and profile.is_primary is distinct from (ranked.position = 1);

create or replace view public.neurospark_correos_duplicates as
select
    link.child_user_id,
    count(*)::integer as duplicate_count,
    jsonb_agg(to_jsonb(link) order by link.is_primary desc, link.updated_at desc, link.id) as records
from public.correos as link
where link.child_user_id is not null
group by link.child_user_id
having count(*) > 1;

create or replace view public.neurospark_profile_duplicates as
select
    'user_id'::text as duplicate_type,
    profile.user_id::text as duplicate_key,
    count(*)::integer as duplicate_count,
    jsonb_agg(to_jsonb(profile) order by profile.is_primary desc, profile.updated_at desc, profile.id) as records
from public.user_profiles as profile
where profile.user_id is not null
group by profile.user_id
having count(*) > 1
union all
select
    'alias'::text,
    lower(profile.alias),
    count(*)::integer,
    jsonb_agg(to_jsonb(profile) order by profile.updated_at desc, profile.id)
from public.user_profiles as profile
where profile.alias is not null
  and btrim(profile.alias) <> ''
group by lower(profile.alias)
having count(*) > 1
union all
select
    'user_email'::text,
    lower(profile.user_email),
    count(*)::integer,
    jsonb_agg(to_jsonb(profile) order by profile.updated_at desc, profile.id)
from public.user_profiles as profile
where profile.user_email is not null
  and btrim(profile.user_email) <> ''
group by lower(profile.user_email)
having count(*) > 1;

