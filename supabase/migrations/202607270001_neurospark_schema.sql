    on public.user_profiles (user_id)
    where user_id is not null and is_primary;

create unique index if not exists ns_correos_child_primary_unique
    on public.correos (child_user_id)
    where child_user_id is not null and is_primary;

create index if not exists ns_profiles_parent_idx
    on public.user_profiles (parent_user_id)
    where parent_user_id is not null;

create index if not exists ns_profiles_email_idx
    on public.user_profiles (lower(user_email))
    where user_email is not null;

create index if not exists ns_profiles_alias_idx
    on public.user_profiles (lower(alias))
    where alias is not null;

create index if not exists ns_correos_parent_idx
    on public.correos (parent_user_id)
    where parent_user_id is not null;

create index if not exists ns_correos_user_email_idx
    on public.correos (lower(user_email))
    where user_email is not null;

create index if not exists ns_correos_parent_email_idx
    on public.correos (lower(parent_email))
    where parent_email is not null;

-- Índices UNIQUE adicionales solo cuando los datos reales lo permiten.
do $$
begin
    if not exists (
        select 1 from public.user_profiles
        where alias is not null and btrim(alias) <> '' and is_primary
        group by lower(alias)
        having count(*) > 1
    ) then
        create unique index if not exists ns_profiles_alias_primary_unique
            on public.user_profiles (lower(alias))
            where alias is not null and is_primary;
    else
        raise notice 'Alias duplicados detectados: se conserva el índice normal y el trigger bloqueará nuevos duplicados.';
    end if;

    if not exists (
        select 1 from public.user_profiles
        where user_email is not null and btrim(user_email) <> '' and is_primary
        group by lower(user_email)
        having count(*) > 1
    ) then
        create unique index if not exists ns_profiles_user_email_primary_unique
            on public.user_profiles (lower(user_email))
            where user_email is not null and is_primary;
    else
        raise notice 'Correos de estudiante duplicados en user_profiles; no se eliminaron.';
    end if;

    if not exists (
        select 1 from public.correos
        where parent_email is not null and btrim(parent_email) <> '' and is_primary
        group by lower(parent_email)
        having count(*) > 1
    ) then
        create unique index if not exists ns_correos_parent_email_primary_unique
            on public.correos (lower(parent_email))
            where parent_email is not null and is_primary;
    else
        raise notice 'Correos parentales duplicados detectados; no se eliminaron.';
    end if;
end
$$;

