checks as (
    select
        'table'::text as object_type,
        expected.object_name,
        to_regclass(expected.object_name) is not null as is_present
    from (values
        ('public.user_profiles'),
        ('public.correos'),
        ('auth.users')
    ) as expected(object_name)
    union all
    select
        'column',
        format('public.%I.%I', required.table_name, required.column_name),
        exists (
            select 1
            from information_schema.columns
            where table_schema = 'public'
              and table_name = required.table_name
              and column_name = required.column_name
        )
    from required_columns as required
    union all
    select
        'function',
        expected.object_name,
        to_regprocedure(expected.object_name) is not null
    from (values
        ('public.is_alias_available(text)'),
        ('public.get_my_family_context()'),
        ('public.ns_set_updated_at()'),
        ('public.ns_enforce_profile_alias()'),
        ('public.ns_enforce_primary_family_link()'),
        ('public.ns_protect_family_identity()')
    ) as expected(object_name)
    union all
    select
        'index',
        expected.object_name,
        to_regclass(expected.object_name) is not null
    from (values
        ('public.ns_profiles_user_primary_unique'),
        ('public.ns_correos_child_primary_unique')
    ) as expected(object_name)
    union all
    select
        'policy',
        format('public.%I.%I', expected.table_name, expected.policy_name),
        exists (
            select 1
            from pg_policies
            where schemaname = 'public'
              and tablename = expected.table_name
              and policyname = expected.policy_name
        )
    from (values
        ('user_profiles', 'ns_family_profiles_select'),
        ('user_profiles', 'ns_family_profiles_update_student'),
        ('correos', 'ns_family_links_select')
    ) as expected(table_name, policy_name)
)
select object_type, object_name, is_present
from checks;

