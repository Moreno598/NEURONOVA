create or replace function public.ns_enforce_profile_alias()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    if new.alias is null or btrim(new.alias) = '' or not new.is_primary then
        return new;
    end if;

    if exists (
        select 1
        from public.user_profiles as existing
        where existing.id is distinct from new.id
          and existing.is_primary
          and lower(existing.alias) = lower(new.alias)
    ) then
        raise exception 'El alias "%" ya está en uso.', new.alias
            using errcode = '23505';
    end if;
    return new;
end
$$;

drop trigger if exists ns_profiles_alias_guard on public.user_profiles;
create trigger ns_profiles_alias_guard
before insert or update of alias, is_primary on public.user_profiles
for each row execute function public.ns_enforce_profile_alias();

create or replace function public.ns_enforce_primary_family_link()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    if not new.is_primary then
        return new;
    end if;

    if new.child_user_id is not null and exists (
        select 1
        from public.correos as existing
        where existing.id is distinct from new.id
          and existing.is_primary
          and existing.child_user_id = new.child_user_id
    ) then
        raise exception 'El hijo ya tiene un vínculo familiar principal.'
            using errcode = '23505';
    end if;

    if new.parent_email is not null
       and btrim(new.parent_email) <> ''
       and exists (
           select 1
           from public.correos as existing
           where existing.id is distinct from new.id
             and existing.is_primary
             and lower(existing.parent_email) = lower(new.parent_email)
       ) then
        raise exception 'El correo del padre/tutor ya tiene un vínculo familiar principal.'
            using errcode = '23505';
    end if;

    return new;
end
$$;

drop trigger if exists ns_correos_family_link_guard on public.correos;
create trigger ns_correos_family_link_guard
before insert or update of child_user_id, parent_email, is_primary on public.correos
for each row execute function public.ns_enforce_primary_family_link();

create or replace function public.ns_protect_family_identity()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    if coalesce(auth.role(), '') = 'authenticated'
       and (
           old.user_id is distinct from new.user_id
           or old.parent_user_id is distinct from new.parent_user_id
           or old.user_email is distinct from new.user_email
           or old.parent_email is distinct from new.parent_email
           or old.age is distinct from new.age
           or old.mode is distinct from new.mode
           or old.is_primary is distinct from new.is_primary
       ) then
        raise exception 'Los datos familiares sensibles no pueden modificarse desde el cliente.'
            using errcode = '42501';
    end if;
    return new;
end
$$;

drop trigger if exists ns_profiles_family_guard on public.user_profiles;
create trigger ns_profiles_family_guard
before update on public.user_profiles
for each row execute function public.ns_protect_family_identity();

