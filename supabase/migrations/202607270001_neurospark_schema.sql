with required_columns(table_name, column_name) as (
    values
        ('user_profiles', 'id'),
        ('user_profiles', 'user_id'),
        ('user_profiles', 'parent_user_id'),
        ('user_profiles', 'user_email'),
        ('user_profiles', 'parent_email'),
        ('user_profiles', 'alias'),
        ('user_profiles', 'full_name'),
        ('user_profiles', 'age'),
        ('user_profiles', 'mode'),
        ('user_profiles', 'state_data'),
        ('user_profiles', 'is_primary'),
        ('correos', 'id'),
        ('correos', 'child_user_id'),
        ('correos', 'parent_user_id'),
        ('correos', 'user_email'),
        ('correos', 'parent_email'),
        ('correos', 'alias'),
        ('correos', 'full_name'),
        ('correos', 'age'),
        ('correos', 'mode'),
        ('correos', 'is_primary')
