$$;

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conname = 'ns_profiles_user_fk'
          and conrelid = 'public.user_profiles'::regclass
    ) then
        alter table public.user_profiles
            add constraint ns_profiles_user_fk
            foreign key (user_id) references auth.users(id)
            on delete cascade not valid;
    end if;
    if not exists (
        select 1 from pg_constraint
        where conname = 'ns_profiles_parent_fk'
          and conrelid = 'public.user_profiles'::regclass
    ) then
        alter table public.user_profiles
            add constraint ns_profiles_parent_fk
            foreign key (parent_user_id) references auth.users(id)
            on delete restrict not valid;
    end if;
    if not exists (
        select 1 from pg_constraint
        where conname = 'ns_correos_child_fk'
          and conrelid = 'public.correos'::regclass
    ) then
        alter table public.correos
            add constraint ns_correos_child_fk
            foreign key (child_user_id) references auth.users(id)
            on delete cascade not valid;
    end if;
    if not exists (
        select 1 from pg_constraint
        where conname = 'ns_correos_parent_fk'
          and conrelid = 'public.correos'::regclass
    ) then
        alter table public.correos
            add constraint ns_correos_parent_fk
            foreign key (parent_user_id) references auth.users(id)
            on delete restrict not valid;
    end if;
end
$$;

do $$
declare
    constraint_name text;
begin
    foreach constraint_name in array array[
        'ns_profiles_age_range',
        'ns_profiles_mode_valid',
        'ns_profiles_mode_matches_age',
        'ns_correos_age_range',
        'ns_correos_mode_valid',
        'ns_correos_mode_matches_age',
        'ns_profiles_user_fk',
        'ns_profiles_parent_fk',
        'ns_correos_child_fk',
        'ns_correos_parent_fk'
    ]
    loop
        begin
            if constraint_name like 'ns_profiles_%'
               and exists (
                   select 1 from pg_constraint
                   where conname = constraint_name
                     and conrelid = 'public.user_profiles'::regclass
               ) then
                execute format(
                    'alter table public.user_profiles validate constraint %I',
                    constraint_name
                );
            elsif constraint_name like 'ns_correos_%'
                  and exists (
                      select 1 from pg_constraint
                      where conname = constraint_name
                        and conrelid = 'public.correos'::regclass
                  ) then
                execute format(
                    'alter table public.correos validate constraint %I',
                    constraint_name
                );
            end if;
        exception
            when check_violation or foreign_key_violation then
                raise notice 'Constraint % quedó NOT VALID por datos históricos incompatibles.',
                    constraint_name;
        end;
    end loop;
end
$$;

-- Nombres de índices UNIQUE de migraciones anteriores. Solo se retiran si son
-- índices independientes; nunca se toca un índice que respalde un constraint.
do $$
declare
    legacy_index text;
    legacy_oid regclass;
begin
    foreach legacy_index in array array[
        'ns_profiles_user_id_unique',
        'ns_profiles_user_email_unique',
        'ns_profiles_alias_unique',
        'ns_profiles_parent_unique',
        'ns_correos_child_unique',
        'ns_correos_user_email_unique',
        'ns_correos_parent_email_unique'
    ]
    loop
        legacy_oid := to_regclass(format('public.%I', legacy_index));
        if legacy_oid is not null
           and not exists (
               select 1
               from pg_constraint
               where conindid = legacy_oid
           ) then
            execute format('drop index if exists public.%I', legacy_index);
            raise notice 'Índice legado public.% retirado; será reemplazado por la regla segura.',
                legacy_index;
        end if;
    end loop;
end
$$;

-- La unicidad se limita a la fila principal; las filas históricas duplicadas
-- permanecen intactas y consultables.
