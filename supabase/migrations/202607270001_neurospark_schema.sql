create or replace view public.neurospark_duplicate_indexes as
with index_catalog as (
    select
        table_class.oid as table_oid,
        table_class.relname as table_name,
        index_meta.indisunique,
        index_meta.indkey::text as indexed_keys,
        index_meta.indclass::text as operator_classes,
        coalesce(pg_get_expr(index_meta.indexprs, index_meta.indrelid), '') as expressions,
        coalesce(pg_get_expr(index_meta.indpred, index_meta.indrelid), '') as predicate,
        index_class.relname as index_name
    from pg_index as index_meta
    join pg_class as table_class on table_class.oid = index_meta.indrelid
    join pg_class as index_class on index_class.oid = index_meta.indexrelid
    join pg_namespace as namespace on namespace.oid = table_class.relnamespace
    where namespace.nspname = 'public'
      and table_class.relname in ('user_profiles', 'correos')
)
select
    table_name,
    indisunique as is_unique,
    indexed_keys,
    expressions,
    predicate,
    count(*)::integer as duplicate_count,
    jsonb_agg(index_name order by index_name) as index_names
from index_catalog
group by table_oid, table_name, indisunique, indexed_keys, operator_classes, expressions, predicate
having count(*) > 1;

create or replace view public.neurospark_duplicate_constraints as
with constraint_catalog as (
    select
        table_class.relname as table_name,
        constraints.contype::text as constraint_type,
        pg_get_constraintdef(constraints.oid, true) as definition,
        constraints.conname as constraint_name
    from pg_constraint as constraints
    join pg_class as table_class on table_class.oid = constraints.conrelid
    join pg_namespace as namespace on namespace.oid = table_class.relnamespace
    where namespace.nspname = 'public'
      and table_class.relname in ('user_profiles', 'correos')
)
select
    table_name,
    constraint_type,
    definition,
    count(*)::integer as duplicate_count,
    jsonb_agg(constraint_name order by constraint_name) as constraint_names
from constraint_catalog
group by table_name, constraint_type, definition
having count(*) > 1;

create or replace view public.neurospark_duplicate_policies as
select
    policies.tablename as table_name,
    policies.cmd,
    policies.roles::text as roles,
    coalesce(policies.qual, '') as using_expression,
    coalesce(policies.with_check, '') as check_expression,
    count(*)::integer as duplicate_count,
    jsonb_agg(policies.policyname order by policies.policyname) as policy_names
from pg_policies as policies
where policies.schemaname = 'public'
  and policies.tablename in ('user_profiles', 'correos')
group by policies.tablename, policies.cmd, policies.roles::text,
         coalesce(policies.qual, ''), coalesce(policies.with_check, '')
having count(*) > 1;

create or replace view public.neurospark_schema_objects as
select
    'function'::text as object_type,
    functions.oid::regprocedure::text as object_name,
    'public'::text as parent_object
from pg_proc as functions
join pg_namespace as namespace on namespace.oid = functions.pronamespace
where namespace.nspname = 'public'
  and functions.proname like 'ns_%'
union all
select
    'trigger',
    triggers.tgname,
    tables.relname
from pg_trigger as triggers
join pg_class as tables on tables.oid = triggers.tgrelid
join pg_namespace as namespace on namespace.oid = tables.relnamespace
where namespace.nspname = 'public'
  and not triggers.tgisinternal
  and tables.relname in ('user_profiles', 'correos')
union all
select
    'view',
    views.viewname,
    views.schemaname
from pg_views as views
where views.schemaname = 'public'
  and views.viewname like 'neurospark_%';

