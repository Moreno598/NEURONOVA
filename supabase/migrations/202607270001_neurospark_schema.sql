-- NeuroSpark: esquema consolidado, reparación de datos y RLS.
-- Compatible con una base nueva y con ejecuciones parciales anteriores.
-- No elimina filas. Los duplicados quedan visibles en vistas de auditoría.

begin;

create or replace function public._ns_safe_jsonb(value text)
returns jsonb
language plpgsql
immutable
set search_path = public, pg_temp
as $$
begin
    if value is null or btrim(value) = '' then
        return '{}'::jsonb;
    end if;
    return value::jsonb;
exception
    when others then
        return jsonb_build_object('legacy_value', value);
end
$$;

